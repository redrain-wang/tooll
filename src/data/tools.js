export function toKebab(s) { return s.replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '') }
export function toModule(path) {
  return path.replace(/^\//, '').replace(/-([a-z])/g, (m, c) => c.toUpperCase()).replace(/^[a-z]/, c => c.toUpperCase())
}

